import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import createSolver from "../web/numlin/cspuz_solver_backend.js";
import { callCspuz } from "../web/sdk/cspuz-api.js";

const source = new URL("../../../../cspuz_core/cspuz_solver_backend/src/puzzle/mod.rs", import.meta.url);
const wasm = new URL("../web/numlin/cspuz_solver_backend.wasm", import.meta.url);
const text = await readFile(process.argv[2] || source, "utf8");
const block = text.match(/\bpuzzle_list!\(puzz_link,([\s\S]*?)\n\);/)?.[1];
if (!block) throw Error("puzz_link puzzle_list! not found");
const module = await createSolver({ wasmBinary: await readFile(wasm) });
const probe = (alias, name) => callCspuz(module, name,
  `https://puzz.link/p?${alias}/not-a-size/not-a-size/`, 2);
const unknown = "__solver_kit_unknown_kind__";
for (const name of ["_solve_problem", "_enumerate_answers_problem"]) {
  if (probe(unknown, name).description !== "unknown puzzle type") throw Error("Unknown-kind control failed");
  // Dispatch precedes deserialization: known malformed URLs must reach their parser.
  const known = probe(name === "_solve_problem" ? "akari" : "heyawake", name);
  if (known.status !== "error" || known.description !== "invalid url") {
    throw Error(`Invalid-URL control failed: ${JSON.stringify(known)}`);
  }
}
const kinds = [];
for (const row of block.matchAll(/\(\s*(\w+),\s*\[([^\]]+)\],\s*"([^"]*)",\s*"([^"]*)"(?:,\s*(enumerable))?\s*\)/g)) {
  const [, key, aliasesText, en, ja] = row;
  const aliases = [...aliasesText.matchAll(/"([^"]+)"/g)].map(m => m[1]).filter(alias => {
    const result = probe(alias, "_solve_problem");
    if (result.description === "unknown puzzle type") return false;
    if (result.status !== "error" || result.description !== "invalid url") {
      throw Error(`Ambiguous dispatch probe for ${alias}: ${JSON.stringify(result)}`);
    }
    return true;
  });
  if (!aliases.length) continue;
  const enumeration = aliases.map(alias => probe(alias, "_enumerate_answers_problem"));
  if (enumeration.some(r => r.status !== "error" || !["invalid url", "unknown puzzle type"].includes(r.description))) {
    throw Error(`Ambiguous enumeration probe for ${key}`);
  }
  if (new Set(enumeration.map(r => r.description)).size !== 1) throw Error(`Enumeration aliases disagree: ${key}`);
  kinds.push({ key, aliases, en, ja, enumerable: enumeration[0].description !== "unknown puzzle type" });
}
if (!kinds.length) throw Error("No supported kinds");
const sha = createHash("sha256").update(await readFile(wasm)).digest("hex");
await writeFile(new URL("../web/sdk/cspuz-kinds.js", import.meta.url),
  `// Generated by web/scripts/gen-cspuz-kinds.mjs at ${new Date().toISOString()}\n// wasm sha256: ${sha}\n` +
  `export const CSPUZ_KINDS = ${JSON.stringify(kinds, null, 2)};\n\n` +
  `export function createCspuzAliasMap() {\n  return new Map(CSPUZ_KINDS.flatMap(({ key, aliases }) => aliases.map(alias => [alias, key])));\n}\n`);
console.log(`Generated ${kinds.length} kinds (${kinds.filter(k => k.enumerable).length} enumerable), wasm ${sha}`);
