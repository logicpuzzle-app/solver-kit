//! 手筋の名前と、難易度スコアでの重み。
//!
//! 名前は `&'static str` 定数にしておき、Recorder のキーと weight の引き数を兼ねる。

// 段階 1: 数字まわりと照射の定石
/// 数字ぶんの照明が置けたので、残りの隣は非照明。0 のかべもこれに含む。
pub const CLUE_FULL: &str = "数字ぶん置けた";
/// 置ける残りが数字ぶんちょうどなので、全部照明。
pub const CLUE_SATURATED: &str = "残りが数字ぶんちょうど";
/// 照明の光の上には照明を置けない(相互照射禁)。
pub const LAMP_RAY: &str = "照明の光の上";

// 段階 2: 救出
/// そのマスを照らせる場所が 1 つしかない。
pub const ONLY_SOURCE: &str = "そこしか照らせない";

// 段階 3: 置いてみて破綻するか
/// そこに照明を置くと、どこかの数字が満たせなくなる。ナナメ手筋・13 手筋などの一般形。
pub const LAMP_BREAKS_CLUE: &str = "置くと数字が足りない";
/// そこに照明を置くと、どこかの白マスが照らせなくなる。
pub const LAMP_BREAKS_LIGHT: &str = "置くと照らせないマスが出る";

// 仮置き
// 段階 4: 場合分け
/// 数字まわりの置き方を全部並べて、どの置き方でも同じになるマス。
pub const CLUE_CASES: &str = "数字まわりの場合分け";

// 段階 5: 照らし手の場合分け
/// 「このマスを照らすのは誰か」で場合分けし、どの場合でも同じになるマス。
pub const SOURCE_CASES: &str = "照らし手の場合分け";

// 仮置き
pub const TRIAL_CONTRADICTION: &str = "仮置きによる矛盾";
pub const TRIAL_ANY_CASE: &str = "いずれにしても確定";

/// 難易度スコアでの重み。手筋を足したらここにも足す。
///
/// puzsq コーパス 2,585 問で座標降下により当てはめた(2026-08-05)。
/// 7 シードの 5-fold CV 一致率で 59.79% → 61.90%。当てはめに使っていない
/// 別の 5 シードでも 59.75% → 62.13% と同じだけ上がったので、過学習ではない。
///
/// ぬりかべでは重みを当てはめると過学習した(訓練 +2.6pt、CV −0.8pt)。
/// 美術館で効くのは、**手筋だけで解ける問題が 9 割を占めていて**
/// 仮置き系の項がほとんど 0 になり、段階の中の順序が発火数だけで決まるため。
/// 実際、仮置きの係数や残りマスの係数を走査しても CV は完全に平坦だった。
///
/// 目を引く 2 つ:
/// - `LAMP_RAY` が 0。10 万回以上発火するが、これは難易度ではなく盤面の広さを
///   測っているだけで、入れると雑音にしかならない
/// - `ONLY_SOURCE`(救出)が 64 と突出。美術館で人が難しいと感じるのは、
///   数字ではなく「どこからも照らせない」を見つける読みだということ
pub fn weight(reason: &str) -> i32 {
    match reason {
        // 盤面の広さを測っているだけなので無償
        LAMP_RAY => 0,
        CLUE_SATURATED | LAMP_BREAKS_LIGHT | CLUE_CASES => 2,
        CLUE_FULL => 8,
        LAMP_BREAKS_CLUE => 12,
        SOURCE_CASES => 24,
        ONLY_SOURCE => 64,
        // 仮置きは専用の係数で課金するので、ここでは 0。
        TRIAL_CONTRADICTION | TRIAL_ANY_CASE => 0,
        _ => 1,
    }
}
